"""
Doom AI brand kit generator.

  python brand/build.py          -> writes the SVGs and the X avatar / banner HTML
  then render the PNGs with headless Chrome (commands printed at the end).

The mark bitmap must match MARK in src/components/Logo.tsx.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
APP_ICON = ROOT.parent / "src" / "app" / "icon.svg"

MARK = [
    ".##############.",
    "#..............#",
    "#..............#",
    "#.#######......#",
    "#.##....##.....#",
    "#.##.::::##....#",
    "#.##.:::::##...#",
    "#.##.:::::##...#",
    "#.##.:::::##...#",
    "#.##.:::::##...#",
    "#.##.::::##.cc.#",
    "#.##....##..cc.#",
    "#.#######...cc.#",
    "#..............#",
    "#..............#",
    ".##############.",
]

# 5×7 pixel letters for the wordmark (I is 3 wide).
FONT = {
    "D": ["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."],
    "O": [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
    "M": ["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"],
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "I": ["###", ".#.", ".#.", ".#.", ".#.", ".#.", "###"],
}


def runs(rows, on, ox=0, oy=0, px=1):
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if on(row[x], x, y):
                s = x
                while x < len(row) and on(row[x], x, y):
                    x += 1
                out.append((ox + s * px, oy + y * px, (x - s) * px, px))
            else:
                x += 1
    return out


def rects(rs, fill):
    return "".join(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}"/>' for x, y, w, h in rs)


def mark_group(ox=0, oy=0):
    ink = runs(MARK, lambda c, x, y: c in "#c" or (c == ":" and (x + y) % 2 == 0), ox, oy)
    return (
        f'<rect x="{ox+2}" y="{oy+16}" width="14" height="1" fill="#000"/>'
        f'<rect x="{ox+16}" y="{oy+2}" width="1" height="14" fill="#000"/>'
        f'<rect x="{ox+15}" y="{oy+15}" width="1" height="1" fill="#000"/>'
        f'<rect x="{ox+1}" y="{oy+1}" width="14" height="14" fill="#fff"/>'
        + rects(ink, "#000")
    )


def word(text, ox, oy, px, fill):
    parts, x = [], ox
    for ch in text:
        g = FONT[ch]
        parts.append(rects(runs(g, lambda c, *_: c == "#", x, oy, px), fill))
        x += (len(g[0]) + 1) * px
    return "".join(parts), x - px


def svg(w, h, body, scale=1):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w*scale}" height="{h*scale}" viewBox="0 0 {w} {h}" '
            f'shape-rendering="crispEdges">{body}</svg>\n')


def build_svgs():
    mark = svg(17, 17, mark_group(), 32)
    (ROOT / "doom-mark.svg").write_text(mark, encoding="utf8")
    APP_ICON.write_text(svg(17, 17, mark_group()), encoding="utf8")

    # lockup: mark (17) + gap + DOOM + inverted AI chip, letters at 2 units per pixel
    doom, end = word("DOOM", 23, 2, 2, "#000")
    ai_x = end + 5
    ai, ai_end = word("AI", ai_x + 2, 2, 2, "#fff")
    chip = f'<rect x="{ai_x}" y="0" width="{ai_end - ai_x + 2}" height="18" fill="#000"/>'
    width = ai_end + 3
    logo = svg(width, 18, mark_group(0, 0) + doom + chip + ai, 10)
    (ROOT / "doom-logo.svg").write_text(logo, encoding="utf8")
    # white-on-black variant for dark backgrounds
    inv = logo.replace('fill="#000"', 'fill="#@@"').replace('fill="#fff"', 'fill="#000"').replace('fill="#@@"', 'fill="#fff"')
    inv = inv.replace('shape-rendering="crispEdges">', f'shape-rendering="crispEdges"><rect x="-4" y="-4" width="{width+8}" height="26" fill="#000"/>', 1)
    inv = inv.replace(f'viewBox="0 0 {width} 18"', f'viewBox="-4 -4 {width+8} 26"')
    (ROOT / "doom-logo-inverse.svg").write_text(inv, encoding="utf8")


FONTS = ('<link href="https://fonts.googleapis.com/css2?family=Pixelify+Sans:wght@400;600;700'
         '&family=IBM+Plex+Mono:wght@400;600&display=swap" rel="stylesheet">')

